#!/usr/bin/env node
/* oxlint-disable */
/* eslint-disable -- Hand-run analysis script that produced this plan's measurements.
   Kept verbatim so its output stays reproducible; it is not shipped code. */
/**
 * Materialize the PRE-fix file tree for the labelled unsafe-selector corpus.
 *
 * Reads `../corpus/manifest.jsonl`, collects every distinct (commit, file) pair, and writes the
 * pre-fix blob (`git show <commit>^:<file>`) into:
 *
 *     <outDir>/<commit>/<repo-relative-path>
 *
 * A candidate detector is then run over `<outDir>` and its findings are scored against
 * `manifest.jsonl` (see ../labelled-corpus.md → "Scoring contract"). Strip the first path segment
 * (the commit) from a detector's reported path to recover the manifest's `file` value.
 *
 * The materialized tree is a build artifact and must never be committed. This script writes a
 * `.gitignore` containing `*` at the root of <outDir>, so the tree is ignored even if <outDir>
 * happens to sit inside the repo. Prefer an out-of-repo path anyway.
 *
 * Idempotent: each run prunes the commit directories it manages and rewrites them from git, so
 * repeated runs converge on the same tree regardless of manifest edits.
 *
 * Usage:
 *   node materialize-corpus.mjs <outDir>
 */

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const MANIFEST = resolve(HERE, '..', 'corpus', 'manifest.jsonl');
const MARKER = '.materialized-unsafe-selector-corpus';

function fail(msg) {
	process.stderr.write(`materialize-corpus: ${msg}\n`);
	process.exit(1);
}

const outArg = process.argv[2];
if (!outArg) {
	fail('missing required <outDir> argument\n  usage: node materialize-corpus.mjs <outDir>');
}
const outDir = resolve(process.cwd(), outArg);

if (!existsSync(MANIFEST)) {
	fail(`manifest not found at ${MANIFEST}`);
}

// Repo root, resolved from this script's own location so the script works from any cwd.
let repoRoot;
try {
	repoRoot = execFileSync('git', ['rev-parse', '--show-toplevel'], { cwd: HERE }).toString().trim();
} catch {
	fail('could not resolve the git repository root from the script location');
}

const rows = readFileSync(MANIFEST, 'utf8')
	.split('\n')
	.filter((l) => l.trim() !== '')
	.map((l, i) => {
		try {
			return JSON.parse(l);
		} catch (e) {
			return fail(`manifest line ${i + 1} is not valid JSON: ${e.message}`);
		}
	});

// Distinct (commit, file) pairs — one materialized file may host several violation sites.
const pairs = [...new Set(rows.map((r) => `${r.commit}\u0000${r.file}`))]
	.map((k) => {
		const [commit, file] = k.split('\u0000');
		return { commit, file };
	})
	.sort((a, b) => a.commit.localeCompare(b.commit) || a.file.localeCompare(b.file));

const commits = [...new Set(pairs.map((p) => p.commit))].sort();

// --- Prune, guarded. Only ever remove directories named after a manifest commit, and only inside
// --- an <outDir> that we own (fresh, or previously marked by this script).
if (existsSync(outDir) && !existsSync(join(outDir, MARKER))) {
	const strays = commits.filter((c) => existsSync(join(outDir, c)));
	if (strays.length > 0) {
		fail(
			`refusing to prune ${outDir}: it contains commit directories but no ${MARKER} marker.\n` +
				'  Delete it by hand, or pick a different <outDir>.',
		);
	}
}
mkdirSync(outDir, { recursive: true });
for (const c of commits) {
	rmSync(join(outDir, c), { recursive: true, force: true });
}

// Belt and braces: the tree must not be committable.
writeFileSync(
	join(outDir, '.gitignore'),
	'# materialized corpus - build artifact, never commit\n*\n',
);
writeFileSync(join(outDir, MARKER), `generated by ${MANIFEST}\ncommits: ${commits.join(' ')}\n`);

let written = 0;
const missing = [];
for (const { commit, file } of pairs) {
	let blob;
	try {
		blob = execFileSync('git', ['show', `${commit}^:${file}`], {
			cwd: repoRoot,
			maxBuffer: 1 << 28,
		});
	} catch {
		missing.push(`${commit}^:${file}`);
		continue;
	}
	const dest = join(outDir, commit, file);
	mkdirSync(dirname(dest), { recursive: true });
	writeFileSync(dest, blob);
	written += 1;
}

if (missing.length > 0) {
	process.stderr.write(
		`materialize-corpus: could not read ${missing.length} blob(s):\n  ${missing.join('\n  ')}\n`,
	);
}

process.stdout.write(
	`materialize-corpus: wrote ${written} file(s) for ${rows.length} violation site(s) ` +
		`across ${commits.length} commit(s) into ${outDir}\n`,
);
process.exit(missing.length > 0 ? 1 : 0);
